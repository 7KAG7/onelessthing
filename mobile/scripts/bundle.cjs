const { mkdirSync } = require('node:fs');
const { join } = require('node:path');
const { spawnSync } = require('node:child_process');
const platform = process.argv[2];
if (!['ios', 'android'].includes(platform)) throw new Error('Choose ios or android.');
const root = join(__dirname, '..');
const output = join(root, '.bundle-output', platform);
mkdirSync(output, { recursive: true });
const result = spawnSync(process.execPath, [require.resolve('react-native/cli.js'), 'bundle', '--platform', platform, '--dev', 'false', '--entry-file', 'index.js', '--bundle-output', join(output, 'main.jsbundle'), '--assets-dest', output, '--reset-cache'], { cwd: root, stdio: 'inherit' });
process.exit(result.status ?? 1);
